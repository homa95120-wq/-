def gen_blocks() -> None:
    doc = json.loads((DATA_DIR / "blocks.json").read_text(encoding="utf-8"))
    blocks = doc["blocks"]
    roles = [
        "CORE", "STORAGE", "DRILL", "CONVEYOR", "JUNCTION", "ROUTER", "SORTER",
        "OVERFLOW", "BRIDGE", "PUMP", "PIPE", "LIQ_ROUT",
        "GEN_FUEL", "GEN_STEAM", "GEN_THERM", "GEN_SOLAR", "PWR_NODE", "BATTERY",
        "CRAFTER", "WALL", "MENDER",
        "TURRET_ITEM", "TURRET_AIR", "TURRET_ARTY", "TURRET_PWR",
    ]
    lines = [
        "// AUTO-GENERATED BY tools/codegen/gen_content.py — DO NOT EDIT",
        f"// Source: Mindustry {doc['source_version']} ({doc['source_commit']}) {doc['source_file']}",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        '#include "simcore/fixed_q16.hpp"',
        "",
        "namespace simcore {",
        "",
        "enum class BlockRole : uint8_t {",
    ]
    for idx, r in enumerate(roles):
        lines.append(f"    {r} = {idx}u,")
    lines += [
        "};",
        "",
        "enum class BlockId : uint16_t {",
    ]
    for b in blocks:
        lines.append(f"    {b['enum_name']} = {b['id']}u,")
    lines += [
        f"    Count = {len(blocks)}u,",
        "    None = 0xFFFFu",
        "};",
        "",
        f"inline constexpr size_t kBlockCount = {len(blocks)}u;",
        "inline constexpr size_t kMaxBlockCostPairs = 5u;",
        "",
        "struct ItemPair {",
        "    uint16_t item_id;",
        "    uint16_t amount;",
        "};",
        "",
        "struct BlockDef {",
        "    uint16_t    id;",
        "    uint8_t     category;",
        "    BlockRole   role;",
        "    uint8_t     size;",
        "    uint8_t     tier;",
        "    int16_t     max_hp;",
        "    uint16_t    param_ticks;",
        "    int16_t     damage;",
        "    uint32_t    color_rgb;",
        "    fx32_t      power_prod_q16;",
        "    fx32_t      power_cons_q16;",
        "    fx32_t      range_tiles_q16;",
        "    ItemPair    in_a;",
        "    ItemPair    in_b;",
        "    ItemPair    out_item;",
        "    uint8_t     cost_count;",
        "    ItemPair    cost[kMaxBlockCostPairs];",
        "    const char* name;",
        "    const char* title_ru;",
        "};",
        "",
        "inline constexpr BlockDef kBlocksTable[kBlockCount] = {",
    ]
    for b in blocks:
        costs = b["cost"]
        padded = list(costs) + [[0xFFFF, 0]] * (5 - len(costs))
        cost_str = ", ".join(f"{{{c[0]}u, {c[1]}u}}" for c in padded[:5])
        ia, ib, oi = b["in_a"], b["in_b"], b["out_item"]
        lines.append(
            f"    {{ {b['id']}u, {b['cat']}u, BlockRole::{b['role']}, {b['size']}u, {b['tier']}u, "
            f"{b['hp']}, {b['param_ticks']}u, {b['damage']}, {b['color']}u, "
            f"{to_q16(b['power_prod'])}, {to_q16(b['power_cons'])}, {to_q16(b['range_tiles'])}, "
            f"{{{ia[0]}u, {ia[1]}u}}, {{{ib[0]}u, {ib[1]}u}}, {{{oi[0]}u, {oi[1]}u}}, "
            f"{len(costs)}u, {{ {cost_str} }}, \"{b['name']}\", \"{b['ru']}\" }},"
        )
    lines += ["};", "", "} // namespace simcore", ""]
    (OUT_DIR / "blocks_table.hpp").write_text("\n".join(lines), encoding="utf-8")


