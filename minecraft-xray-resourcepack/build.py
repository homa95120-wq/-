#!/usr/bin/env python3
"""Build the animated video-texture pack for Minecraft Java 1.21.10.

Every block keeps the video (and the video's sound), but blocks are now
recognisable: each block id is mapped to a *family* (see families.json,
generated by make_block_textures.py) and every family has its own animated
strip = darkened/tinted video frames + a pixel-art badge + a colour frame.
Water and lava use baked tinted strips of the same clip.

The strips, badges and families.json are produced by make_block_textures.py;
this script only validates and packages them (stdlib only, no Pillow/ffmpeg).
"""

from __future__ import annotations

import json
import struct
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "dist" / "AnimeGirlBlocks-1.21.10.zip"
BLOCK_IDS = ROOT / "block_ids.json"
SOUND_EVENTS = ROOT / "sound_events.json"
PACK_META = ROOT / "pack.mcmeta"
FAMILIES = ROOT / "assets" / "families.json"
FAM_DIR = ROOT / "assets" / "families"
POSTER = ROOT / "assets" / "poster.png"
AUDIO = ROOT / "assets" / "video.ogg"
WATER_STRIP = ROOT / "assets" / "anime_girl_water.png"
LAVA_STRIP = ROOT / "assets" / "anime_girl_lava.png"

FLUID_BLOCKS = {"water": "water", "bubble_column": "water", "lava": "lava"}
FLUID_TEXTURES = {
    "water": ("water_still.png", "water_flow.png", "water_overlay.png"),
    "lava": ("lava_still.png", "lava_flow.png"),
}

# --- Sound toggles -----------------------------------------------------------
# The video audio replaces these sounds. Flip a flag (or drop a verb, e.g.
# "step", if footsteps restarting the track get too chaotic) and rebuild.
ENABLE_BLOCK_SOUNDS = True
ENABLE_DISC_SOUNDS = True
BLOCK_SOUND_VERBS = ("break", "place", "step", "hit", "fall")
SOUND_NAME = "minecraft:video"  # -> assets/minecraft/sounds/video.ogg
SOUND_PATH = "assets/minecraft/sounds/video.ogg"
SOUNDS_JSON_PATH = "assets/minecraft/sounds.json"


def png_info(data: bytes, label: str) -> tuple[int, int]:
    """Return (width, height) of a PNG, failing loudly if it is not one."""
    if not data.startswith(b"\x89PNG\r\n\x1a\n") or data[12:16] != b"IHDR":
        raise SystemExit(f"{label} is not a valid PNG")
    width, height = struct.unpack(">II", data[16:24])
    if width == 0 or height == 0 or height % width != 0:
        raise SystemExit(
            f"{label} must be a vertical strip of square frames, got {width}x{height}"
        )
    return width, height


def build_sounds_json(block_events: list[str], disc_events: list[str]) -> bytes:
    sounds: dict[str, object] = {}
    if ENABLE_BLOCK_SOUNDS:
        for event in block_events:
            if event.rsplit(".", 1)[1] in BLOCK_SOUND_VERBS:
                sounds[event] = {
                    "sounds": [{"name": SOUND_NAME}],
                    "replace": True,
                }
    if ENABLE_DISC_SOUNDS:
        for event in disc_events:
            sounds[event] = {
                "sounds": [{"name": SOUND_NAME, "stream": True}],
                "replace": True,
            }
    if not sounds:
        raise SystemExit("no sound events selected; check the sound toggles")
    return json.dumps(sounds, separators=(",", ":")).encode("utf-8")


def main() -> None:
    required_files = (
        PACK_META, BLOCK_IDS, SOUND_EVENTS, FAMILIES, POSTER, AUDIO,
        WATER_STRIP, LAVA_STRIP,
    )
    missing_files = [str(p) for p in required_files if not p.is_file()]
    if missing_files:
        raise SystemExit(
            f"missing input files: {missing_files} "
            "(regenerate textures with make_block_textures.py)"
        )

    metadata = json.loads(PACK_META.read_text(encoding="utf-8"))
    pack = metadata.get("pack", {})
    if pack.get("min_format") != [69, 0] or pack.get("max_format") != [69, 0]:
        raise SystemExit("pack.mcmeta must target resource pack format 69.0 (Java 1.21.10)")

    block_ids = json.loads(BLOCK_IDS.read_text(encoding="utf-8"))
    if len(block_ids) < 1000 or len(block_ids) != len(set(block_ids)):
        raise SystemExit("block_ids.json must contain a unique list of Minecraft block IDs")
    if any(not name or "/" in name or ":" in name for name in block_ids):
        raise SystemExit("Block IDs must be unnamespaced names without path separators")

    sound_events = json.loads(SOUND_EVENTS.read_text(encoding="utf-8"))
    block_events = sound_events.get("block", [])
    disc_events = sound_events.get("discs", [])
    if len(block_events) < 100 or not disc_events:
        raise SystemExit("sound_events.json must list block and disc sound events")

    fam_doc = json.loads(FAMILIES.read_text(encoding="utf-8"))
    families = fam_doc["families"]
    mapping = fam_doc["blocks"]
    fluid_meta = fam_doc["fluids"]

    solid_blocks = [b for b in block_ids if b not in FLUID_BLOCKS and b != "air"]
    unmapped = [b for b in solid_blocks if b not in mapping]
    if unmapped:
        raise SystemExit(f"blocks without a family: {unmapped[:10]} ... "
                         "rerun make_block_textures.py")
    used = sorted({mapping[b] for b in solid_blocks})
    unknown_only = [b for b in solid_blocks if mapping[b] == "unknown"]
    if len(unknown_only) > 40:
        raise SystemExit(f"{len(unknown_only)} blocks fell back to the generic "
                         "'unknown' family; extend the family table")

    fam_bytes: dict[str, bytes] = {}
    fam_meta_bytes: dict[str, bytes] = {}
    for key in used:
        spec = families[key]
        path = FAM_DIR / f"{key}.png"
        if not path.is_file():
            raise SystemExit(f"missing family strip {path}; rerun make_block_textures.py")
        data = path.read_bytes()
        width, height = png_info(data, f"families/{key}.png")
        if width != spec["size"] or height // width != spec["frames"]:
            raise SystemExit(
                f"families/{key}.png is {width}x{height} but families.json says "
                f"{spec['size']}px x {spec['frames']} frames; rerun make_block_textures.py"
            )
        frametime = spec["frametime"]
        if not isinstance(frametime, int) or frametime < 1:
            raise SystemExit(f"family {key} needs frametime >= 1")
        fam_bytes[key] = data
        fam_meta_bytes[key] = json.dumps(
            {"animation": {"frametime": frametime}}, separators=(",", ":")
        ).encode("utf-8")

    water_bytes = WATER_STRIP.read_bytes()
    lava_bytes = LAVA_STRIP.read_bytes()
    for data, label in ((water_bytes, "anime_girl_water.png"),
                        (lava_bytes, "anime_girl_lava.png")):
        width, height = png_info(data, label)
        if height // width != fluid_meta["frames"]:
            raise SystemExit(f"{label} frame count != families.json fluids.frames")
    fluid_meta_bytes = json.dumps(
        {"animation": {"frametime": fluid_meta["frametime"]}}, separators=(",", ":")
    ).encode("utf-8")

    audio_bytes = AUDIO.read_bytes()
    if not audio_bytes.startswith(b"OggS"):
        raise SystemExit("video.ogg is not an Ogg file")

    poster_bytes = POSTER.read_bytes()
    png_info(poster_bytes, "poster.png")

    sounds_bytes = build_sounds_json(block_events, disc_events)
    sound_event_total = len(json.loads(sounds_bytes))

    def family_model(key: str) -> bytes:
        return json.dumps({
            "parent": "minecraft:block/cube_all",
            "textures": {"all": f"minecraft:block/fam/{key}"},
        }, separators=(",", ":")).encode("utf-8")

    def blockstate_for(model: str) -> bytes:
        return json.dumps({
            "multipart": [{"apply": {"model": model}}]
        }, separators=(",", ":")).encode("utf-8")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(OUTPUT, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        archive.writestr("pack.mcmeta", PACK_META.read_bytes())
        archive.writestr("pack.png", poster_bytes)
        for key in used:
            archive.writestr(f"assets/minecraft/textures/block/fam/{key}.png",
                             fam_bytes[key])
            archive.writestr(f"assets/minecraft/textures/block/fam/{key}.png.mcmeta",
                             fam_meta_bytes[key])
            archive.writestr(f"assets/minecraft/models/block/fam/{key}.json",
                             family_model(key))
        for block_id in solid_blocks:
            key = mapping[block_id]
            model = f"minecraft:block/fam/{key}"
            archive.writestr(f"assets/minecraft/blockstates/{block_id}.json",
                             blockstate_for(model))
            archive.writestr(
                f"assets/minecraft/models/item/{block_id}.json",
                json.dumps({"parent": model}, separators=(",", ":")).encode("utf-8"),
            )
        # fluids: cube blockstate + the five fluid textures vanilla's fluid
        # renderer reads, all from the baked tinted strips of the same clip
        for fluid in dict.fromkeys(FLUID_BLOCKS.values()):
            model_bytes = json.dumps({
                "parent": "minecraft:block/cube_all",
                "textures": {"all": f"minecraft:block/anime_girl_{fluid}"},
            }, separators=(",", ":")).encode("utf-8")
            archive.writestr(f"assets/minecraft/models/block/{fluid}_cube.json",
                             model_bytes)
            for block_id, block_fluid in FLUID_BLOCKS.items():
                if block_fluid != fluid or block_id not in block_ids:
                    continue
                archive.writestr(f"assets/minecraft/blockstates/{block_id}.json",
                                 blockstate_for(f"minecraft:block/{fluid}_cube"))
                archive.writestr(
                    f"assets/minecraft/models/item/{block_id}.json",
                    json.dumps({"parent": f"minecraft:block/{fluid}_cube"},
                               separators=(",", ":")).encode("utf-8"),
                )
        for fluid, names in FLUID_TEXTURES.items():
            data = water_bytes if fluid == "water" else lava_bytes
            for name in names:
                archive.writestr(f"assets/minecraft/textures/block/{name}", data)
                archive.writestr(f"assets/minecraft/textures/block/{name}.mcmeta",
                                 fluid_meta_bytes)
        archive.writestr(SOUND_PATH, audio_bytes)
        archive.writestr(SOUNDS_JSON_PATH, sounds_bytes)

    with ZipFile(OUTPUT) as archive:
        names = set(archive.namelist())
        required = {
            "pack.mcmeta",
            "pack.png",
            "assets/minecraft/textures/block/fam/stone.png",
            "assets/minecraft/textures/block/fam/stone.png.mcmeta",
            "assets/minecraft/models/block/fam/stone.json",
            "assets/minecraft/blockstates/stone.json",
            "assets/minecraft/blockstates/diamond_ore.json",
            "assets/minecraft/blockstates/chest.json",
            "assets/minecraft/blockstates/water.json",
            "assets/minecraft/blockstates/lava.json",
            "assets/minecraft/models/item/stone.json",
            "assets/minecraft/models/item/diamond_ore.json",
            SOUND_PATH,
            SOUNDS_JSON_PATH,
        }
        for fluid, tex_names in FLUID_TEXTURES.items():
            for name in tex_names:
                required.add(f"assets/minecraft/textures/block/{name}")
                required.add(f"assets/minecraft/textures/block/{name}.mcmeta")
        missing = required - names
        if missing:
            raise SystemExit(f"Archive is missing required files: {sorted(missing)}")
        if "assets/minecraft/blockstates/air.json" in names:
            raise SystemExit("Air must not be replaced")
        for name in names:
            if name.endswith((".json", ".mcmeta")):
                json.loads(archive.read(name))
        # every blockstate must point at a model that exists in the archive
        for name in list(names):
            if name.startswith("assets/minecraft/blockstates/"):
                doc = json.loads(archive.read(name))
                for part in doc.get("multipart", []):
                    model = part["apply"]["model"]
                    model_path = "assets/minecraft/models/" + model.split(":", 1)[1] + ".json"
                    if model_path not in names:
                        raise SystemExit(f"{name} references missing model {model}")
        packed_sounds = json.loads(archive.read(SOUNDS_JSON_PATH))
        if len(packed_sounds) != sound_event_total:
            raise SystemExit("sounds.json event count mismatch in archive")
        for event, entry in packed_sounds.items():
            if entry.get("replace") is not True or not entry.get("sounds"):
                raise SystemExit(f"sounds.json entry {event} must replace vanilla sounds")

    hi = [k for k in used if families[k]["tier"] == "hi"]
    print(
        f"Built {OUTPUT.relative_to(ROOT)} "
        f"({OUTPUT.stat().st_size} bytes; {len(solid_blocks)} block types replaced; "
        f"{len(used)} families ({len(hi)} hi-res); "
        f"{sound_event_total} sound events)"
    )


if __name__ == "__main__":
    main()
