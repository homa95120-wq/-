from __future__ import annotations
import json
from decimal import Decimal, getcontext
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = ROOT / "content" / "data"
OUT_DIR = ROOT / "simcore" / "include" / "simcore" / "generated"

Q16_ONE = 65536


def to_q16(dec_str: str) -> int:
    """Точный перевод десятичной строки в Q16.16 (half-away-from-zero) через Fraction."""
    frac = Fraction(str(dec_str)) * Q16_ONE
    num, den = frac.numerator, frac.denominator
    if num >= 0:
        return (2 * num + den) // (2 * den)
    pos = -num
    return -((2 * pos + den) // (2 * den))


def compute_sin_lut_q16(n: int = 1024) -> list[int]:
    """Предвычисляет sin(2*pi*i/n) в Q16.16 через ряд Тейлора в Decimal (точность 50 знаков)."""
    getcontext().prec = 50
    # Высокоточная константа pi (Machin-like)
    pi = Decimal("3.14159265358979323846264338327950288419716939937510")
    two_pi = Decimal(2) * pi
    out: list[int] = []
    for i in range(n):
        x = (two_pi * Decimal(i)) / Decimal(n)
        # Приведение к [-pi, pi]
        if x > pi:
            x -= two_pi
        term = x
        acc = x
        x2 = x * x
        for k in range(1, 28):
            term = -term * x2 / Decimal((2 * k) * (2 * k + 1))
            acc += term
        scaled = acc * Decimal(Q16_ONE)
        if scaled >= 0:
            q = int((scaled + Decimal("0.5")).to_integral_value(rounding="ROUND_FLOOR"))
        else:
            q = -int(((-scaled) + Decimal("0.5")).to_integral_value(rounding="ROUND_FLOOR"))
        out.append(q)
    return out


def gen_trig_lut() -> None:
    lut = compute_sin_lut_q16(1024)
    lines = [
        "// AUTO-GENERATED BY tools/codegen/gen_content.py — DO NOT EDIT",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#pragma once",
        "#include <stdint.h>",
        '#include "simcore/fixed_q16.hpp"',
        "",
        "namespace simcore {",
        "",
        "inline constexpr uint32_t kTrigLutBits = 10u;",
        "inline constexpr uint32_t kTrigLutSize = 1024u;",
        "inline constexpr uint32_t kTrigLutMask = 1023u;",
        "",
        "inline constexpr fx32_t kSinLutQ16[kTrigLutSize] = {",
    ]
    for row in range(0, 1024, 16):
        chunk = ", ".join(f"{lut[i]:6d}" for i in range(row, row + 16))
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        "constexpr fx32_t fx_sin_bam10(uint32_t angle_bam10) noexcept {",
        "    return kSinLutQ16[angle_bam10 & kTrigLutMask];",
        "}",
        "",
        "constexpr fx32_t fx_cos_bam10(uint32_t angle_bam10) noexcept {",
        "    return kSinLutQ16[(angle_bam10 + (kTrigLutSize / 4u)) & kTrigLutMask];",
        "}",
        "",
        "} // namespace simcore",
        "",
    ]
    (OUT_DIR / "trig_lut.hpp").write_text("\n".join(lines), encoding="utf-8")


def gen_items() -> None:
    doc = json.loads((DATA_DIR / "items.json").read_text(encoding="utf-8"))
    items = doc["items"]
    lines = [
        "// AUTO-GENERATED BY tools/codegen/gen_content.py — DO NOT EDIT",
        f"// Source: Mindustry {doc['source_version']} ({doc['source_commit']}) {doc['source_file']}",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        '#include "simcore/fixed_q16.hpp"',
        "",
        "namespace simcore {",
        "",
        "inline constexpr uint8_t ITEM_FLAG_BUILDABLE       = 1u << 0;",
        "inline constexpr uint8_t ITEM_FLAG_ALWAYS_UNLOCKED = 1u << 1;",
        "inline constexpr uint8_t ITEM_FLAG_LOW_PRIORITY    = 1u << 2;",
        "inline constexpr uint8_t ITEM_FLAG_HIDDEN          = 1u << 3;",
        "inline constexpr uint8_t ITEM_FLAG_SERPULO         = 1u << 4;",
        "inline constexpr uint8_t ITEM_FLAG_EREKIR          = 1u << 5;",
        "",
        "enum class ItemId : uint16_t {",
    ]
    for it in items:
        lines.append(f"    {it['enum_name']} = {it['id']}u, // \"{it['name']}\"")
    lines += [
        f"    Count = {len(items)}u,",
        "    None = 0xFFFFu",
        "};",
        "",
        f"inline constexpr size_t kItemCount = {len(items)}u;",
        "inline constexpr size_t kSerpuloItemCount = 16u;",
        "",
        "struct ItemDef {",
        "    uint16_t    id;",
        "    uint8_t     hardness;",
        "    uint8_t     flags;",
        "    uint32_t    color_rgb;",
        "    fx32_t      cost_q16;",
        "    fx32_t      explosiveness_q16;",
        "    fx32_t      flammability_q16;",
        "    fx32_t      radioactivity_q16;",
        "    fx32_t      charge_q16;",
        "    fx32_t      health_scaling_q16;",
        "    const char* name;",
        "    const char* title_ru;",
        "};",
        "",
        "inline constexpr ItemDef kItemsTable[kItemCount] = {",
    ]
    for it in items:
        fl = []
        if it["buildable"]:
            fl.append("ITEM_FLAG_BUILDABLE")
        if it["always_unlocked"]:
            fl.append("ITEM_FLAG_ALWAYS_UNLOCKED")
        if it["low_priority"]:
            fl.append("ITEM_FLAG_LOW_PRIORITY")
        if it["hidden"]:
            fl.append("ITEM_FLAG_HIDDEN")
        if it["serpulo"]:
            fl.append("ITEM_FLAG_SERPULO")
        if it["erekir"]:
            fl.append("ITEM_FLAG_EREKIR")
        flag_expr = "0u" if not fl else f"static_cast<uint8_t>({' | '.join(fl)})"
        lines.append(
            f"    /* [{it['id']:2d}] {it['name']:14s} */ {{ "
            f"{it['id']}u, {it['hardness']}u, {flag_expr}, {it['color']}u, "
            f"{to_q16(it['cost'])}, {to_q16(it['explosiveness'])}, {to_q16(it['flammability'])}, "
            f"{to_q16(it['radioactivity'])}, {to_q16(it['charge'])}, {to_q16(it['health_scaling'])}, "
            f"\"{it['name']}\", \"{it['ru']}\" }},"
        )
    lines += [
        "};",
        "",
        "} // namespace simcore",
        "",
    ]
    (OUT_DIR / "items_table.hpp").write_text("\n".join(lines), encoding="utf-8")


